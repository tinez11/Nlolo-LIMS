#!/usr/bin/env bash
# ELIMU -- the five-year education plan, set up from the printed rate card and sold to one client.
#
# Authored 2026-10-15. Real REST API, real Keycloak token, the way seed-dev-data.sh works.
#
# THE RATE CARD, as printed ("Muda wa Mkataba wa Bima: MIAKA MITANO"):
#
#   Ada ya Bima kwa Muda   Jumla ya Ada kwa miaka 5   MAFAO
#          15,300                   918,000          1,000,000
#          30,500                 1,830,000          2,000,000
#          76,000                 4,560,000          5,000,000
#         152,000                 9,120,000         10,000,000
#         228,800                13,728,000         15,000,000
#         304,000                18,240,000         20,000,000
#
# WHAT THE COLUMNS MEAN, confirmed by arithmetic rather than assumed: the first column is the
# MONTHLY premium, and premium x 60 months equals the middle column exactly on all six rows.
# MAFAO is the benefit -- the sum assured. The client pays in roughly 91.2% to 91.8% of what the
# plan pays out, which is what makes it a savings contract rather than pure cover.
#
# HOW IT IS PRICED HERE. The platform prices from a rate per mille PER YEAR, times a sum-assured
# band multiplier, divided by twelve for a monthly instalment. The card is not generated by one
# formula -- it works out at 15,200 to 15,300 per million per month depending on the band -- so
# the base rate is the common 182.4 per mille a year and three bands carry a small multiplier.
#
# THE CARD IS NOT REPRODUCED TO THE SHILLING ON THREE ROWS, and that is a limit of the data model
# rather than a rounding choice: the multiplier column holds four decimal places. The differences:
#
#    1,000,000  card 15,300   computed 15,300.32   +0.32
#    2,000,000  card 30,500   computed 30,500.32   +0.32
#    5,000,000  card 76,000   computed 76,000.00    exact
#   10,000,000  card 152,000  computed 152,000.00   exact
#   15,000,000  card 228,800  computed 228,798.00  -2.00
#   20,000,000  card 304,000  computed 304,000.00   exact
#
# If the business needs all six exact, the card has to become six priced options rather than a
# rate -- say so and it is a different setup, not a tweak to this one.
#
# Run it with the dev stack up (infra, backend on 8080, Keycloak on 8081):
#   ./scripts/elimu-education-demo.sh
set -euo pipefail
cd "$(dirname "$0")/.."

KEYCLOAK="${KEYCLOAK_URL:-http://localhost:8081}"
API="${API_URL:-http://localhost:8080}"

# The client: an existing, KYC-verified party. MALE, born 1990-02-01, so 36 at entry.
CLIENT_PARTY_ID="${ELIMU_CLIENT_PARTY_ID:-8b077231-ef62-4a5c-8ab0-9343d3d1f307}"
# The 5,000,000 band: a row the platform reproduces EXACTLY, so the demo shows 76,000 against a
# card that says 76,000.
SUM_ASSURED="${ELIMU_SUM_ASSURED:-5000000.00}"
TERM_MONTHS=60

uuid() {
  if [ -r /proc/sys/kernel/random/uuid ]; then cat /proc/sys/kernel/random/uuid
  elif command -v uuidgen >/dev/null 2>&1; then uuidgen | tr 'A-Z' 'a-z'
  else od -An -N16 -tx1 /dev/urandom | tr -d ' \n' | sed -E 's/(.{8})(.{4})(.{4})(.{4})(.{12})/\1-\2-\3-\4-\5/'
  fi
}

token_for() {
  curl -sf -X POST "$KEYCLOAK/realms/$1/protocol/openid-connect/token" \
    -d grant_type=password -d client_id=lifeplatform-app -d client_secret="$3" \
    -d username="$2" -d password=devpassword \
  | sed 's/.*"access_token":"\([^"]*\)".*/\1/'
}

api() {
  local token="$1" method="$2" path="$3" body="${4:-}"
  if [ -n "$body" ]; then
    curl -sf -X "$method" "$API$path" -H "Authorization: Bearer $token" \
      -H 'Content-Type: application/json' -H "Idempotency-Key: $(uuid)" -d "$body"
  else
    curl -sf -X "$method" "$API$path" -H "Authorization: Bearer $token"
  fi
}

jsonval() { grep -o "\"$2\" *: *\"[^\"]*\"" <<<"$1" | head -1 | sed -E 's/.*: *"([^"]*)"/\1/'; }

STAFF_SECRET=$(grep -o '"secret" *: *"[^"]*"' keycloak/staff-realm.json | head -1 | cut -d'"' -f4)
STAFF_ADMIN_TOKEN=$(token_for staff staff.admin "$STAFF_SECRET")
STAFF_FINANCE_TOKEN=$(token_for staff staff.finance "$STAFF_SECRET")
STAFF_SENIOR_TOKEN=$(token_for staff staff.senior "$STAFF_SECRET")
STAFF_UNDERWRITER_TOKEN=$(token_for staff staff.underwriter "$STAFF_SECRET")
[ -n "$STAFF_ADMIN_TOKEN" ] || { echo "Could not get a staff.admin token" >&2; exit 1; }

SUFFIX=$(date +%H%M%S)

echo "=== Step 1: Author the Elimu product ==="
PRODUCT_JSON=$(api "$STAFF_ADMIN_TOKEN" POST "/products" \
  "{\"productCode\":\"ELIMU-$SUFFIX\",\"productName\":\"Elimu Education Plan\",\"category\":\"EDUCATION_SAVINGS\",\"portfolioCode\":\"END\",\"defaultCurrency\":\"TZS\"}")
PRODUCT_ID=$(jsonval "$PRODUCT_JSON" productId)
echo "elimuProductId=$PRODUCT_ID"
[ -n "$PRODUCT_ID" ] || { echo "Product was not created: $PRODUCT_JSON" >&2; exit 1; }

echo "=== Step 2: Publish the version carrying the rate card ==="
# baseRates      : 182.4 per mille PER YEAR. Six rows so every sex and smoker status resolves --
#                  the lookup is keyed on all three and refuses a life no cell covers.
# ratingTable    : the six sum-assured bands and NOTHING ELSE. Only three carry a multiplier; the
#                  other three sit on the base rate exactly. No AGE factor: age is already a key
#                  of the base rate table, and the platform refuses a version carrying both
#                  rather than let the dimension be counted twice. One OCCUPATION_CLASS band at
#                  1.0 is there for the QUOTE screen only: issuance prices without it, but a
#                  quote names an occupation and is refused when no band matches.
# eligibility    : ages 18-60 and a term of exactly 60 months. MIAKA MITANO is the only term the
#                  card offers, and the bounds are what stop anyone selling another.
# payoutSchedule : MATURITY, PERCENT_OF_SA 100 -- the plan pays the MAFAO at the end of five years.
VERSION_RESP=$(curl -sfi -X POST "$API/products/$PRODUCT_ID/versions" \
  -H "Authorization: Bearer $STAFF_ADMIN_TOKEN" -H 'Content-Type: application/json' \
  -H "Idempotency-Key: $(uuid)" -d '{
    "ifrsMeasurementModel":"GMM","effectiveDate":"2020-01-01",
    "payoutTerms":{"freeLookDays":15},
    "payoutSchedule":[{"kind":"MATURITY","amountBasis":"PERCENT_OF_SA","amountValue":100}],
    "tiraFiling":{"reference":"TIRA/DEMO/ELIMU/0001","approvalDate":"2020-01-01"},
    "eligibility":{"minEntryAge":18,"maxEntryAge":60,"minTermMonths":60,"maxTermMonths":60},
    "baseRates":[
      {"ageFrom":18,"ageTo":60,"sex":"MALE","smokerStatus":"NON_SMOKER","ratePerMille":182.4},
      {"ageFrom":18,"ageTo":60,"sex":"MALE","smokerStatus":"SMOKER","ratePerMille":182.4},
      {"ageFrom":18,"ageTo":60,"sex":"MALE","smokerStatus":"UNKNOWN","ratePerMille":182.4},
      {"ageFrom":18,"ageTo":60,"sex":"FEMALE","smokerStatus":"NON_SMOKER","ratePerMille":182.4},
      {"ageFrom":18,"ageTo":60,"sex":"FEMALE","smokerStatus":"SMOKER","ratePerMille":182.4},
      {"ageFrom":18,"ageTo":60,"sex":"FEMALE","smokerStatus":"UNKNOWN","ratePerMille":182.4}
    ],
    "ratingTable":[
      {"factorType":"OCCUPATION_CLASS","band":"STANDARD","multiplier":1.0},
      {"factorType":"SUM_ASSURED_BAND","band":"1M","multiplier":1.0066,"sumAssuredFrom":1000000,"sumAssuredTo":1999999.99},
      {"factorType":"SUM_ASSURED_BAND","band":"2M","multiplier":1.0033,"sumAssuredFrom":2000000,"sumAssuredTo":4999999.99},
      {"factorType":"SUM_ASSURED_BAND","band":"5M","multiplier":1.0000,"sumAssuredFrom":5000000,"sumAssuredTo":9999999.99},
      {"factorType":"SUM_ASSURED_BAND","band":"10M","multiplier":1.0000,"sumAssuredFrom":10000000,"sumAssuredTo":14999999.99},
      {"factorType":"SUM_ASSURED_BAND","band":"15M","multiplier":1.0035,"sumAssuredFrom":15000000,"sumAssuredTo":19999999.99},
      {"factorType":"SUM_ASSURED_BAND","band":"20M","multiplier":1.0000,"sumAssuredFrom":20000000,"sumAssuredTo":20000000}
    ],
    "benefitSchedule":[{"benefitType":"DEATH","calculationMethod":"SUM_ASSURED"}]
  }')
echo "$VERSION_RESP" | head -1

SNAPSHOT_JSON=$(api "$STAFF_FINANCE_TOKEN" GET "/products/$PRODUCT_ID/active-snapshot")
VERSION_ID=$(jsonval "$SNAPSHOT_JSON" productVersionId)
echo "elimuProductVersionId=$VERSION_ID"
[ -n "$VERSION_ID" ] || { echo "No active snapshot: $SNAPSHOT_JSON" >&2; exit 1; }

echo "=== Step 3: Quote it, and check the quote against the card ==="
QUOTE_JSON=$(api "$STAFF_FINANCE_TOKEN" POST "/products/$PRODUCT_ID/premium-quote" \
  "{\"sumAssuredAmount\":$SUM_ASSURED,\"sumAssuredCurrency\":\"TZS\",
    \"dateOfBirth\":\"1990-02-01\",\"sex\":\"MALE\",\"smokerStatus\":\"NON_SMOKER\",
    \"occupationClass\":\"STANDARD\",
    \"frequency\":\"MONTHLY\",\"policyTermMonths\":$TERM_MONTHS}" || true)
echo "quote: $QUOTE_JSON" | head -c 500; echo

echo "=== Step 4: Open an underwriting case for the client ==="
CASE_JSON=$(api "$STAFF_SENIOR_TOKEN" POST "/underwriting/cases" \
  "{\"applicantPartyId\":\"$CLIENT_PARTY_ID\",\"productId\":\"$PRODUCT_ID\",\"productVersionId\":\"$VERSION_ID\",
    \"sumAssured\":{\"amount\":\"$SUM_ASSURED\",\"currencyCode\":\"TZS\"},
    \"requestedTermMonths\":$TERM_MONTHS,\"premiumFrequency\":\"MONTHLY\"}")
CASE_ID=$(jsonval "$CASE_JSON" caseId)
echo "caseId=$CASE_ID"
[ -n "$CASE_ID" ] || { echo "Case was not opened: $CASE_JSON" >&2; exit 1; }

echo "=== Step 5: Assess and decide ==="
ASSESSMENT_JSON=$(api "$STAFF_SENIOR_TOKEN" POST "/underwriting/cases/$CASE_ID/assessments" \
  '{"assessmentType":"MEDICAL","findings":"Standard risk, no adverse findings","riskScore":10}')
echo "recommendationOutcome=$(jsonval "$ASSESSMENT_JSON" recommendationOutcome)"

DECISION_JSON=$(api "$STAFF_UNDERWRITER_TOKEN" POST "/underwriting/cases/$CASE_ID/decision" \
  '{"outcome":"ACCEPT","reason":"Elimu demo: standard risk, in line with the recommendation"}')
echo "decisionOutcome=$(jsonval "$DECISION_JSON" decisionOutcome)"

echo "=== Step 6: Wait for the policy ==="
POLICY_NUMBER=""
for i in $(seq 1 30); do
  SEARCH_JSON=$(api "$STAFF_FINANCE_TOKEN" GET "/policies?policyholderPartyId=$CLIENT_PARTY_ID")
  CANDIDATE=$(jsonval "$SEARCH_JSON" policyNumber)
  if [ -n "$CANDIDATE" ]; then POLICY_NUMBER="$CANDIDATE"; break; fi
  sleep 1
done
echo "policyNumber=$POLICY_NUMBER"

echo
echo "Elimu is configured and one plan is sold."
echo "  Product:  $PRODUCT_ID"
echo "  Version:  $VERSION_ID"
echo "  Policy:   $POLICY_NUMBER"
echo "  Benefit:  TZS $SUM_ASSURED over $TERM_MONTHS months"
echo "  Expected: 76,000 a month -- the card's 5,000,000 row"
